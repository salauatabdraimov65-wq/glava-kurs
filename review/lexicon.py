def numbers(s: str) -> list[str]:
    return [n.replace(",", ".").rstrip(".") for n in NUM_RE.findall(s)]


def has(stems: list[str], s: str) -> list[str]:
    s = " " + s.lower().replace("ё", "е") + " "
    return [w for w in stems if w in s]
